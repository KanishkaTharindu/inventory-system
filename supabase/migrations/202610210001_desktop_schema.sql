-- Office Stock desktop schema for Supabase. Apply once in Supabase SQL Editor.
-- Never put a service_role or secret key in the desktop application.
begin;

create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  name varchar(120) not null, code varchar(10) not null unique,
  type varchar(10) not null default 'branch' check (type in ('main','branch')),
  address varchar(250) not null default '', phone varchar(40) not null default '', active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create unique index if not exists one_main_office on public.branches(type) where type='main';

create table if not exists public.roles (
  key varchar(40) primary key, name varchar(40) not null, name_key varchar(40) not null unique,
  description varchar(200) not null default '', side varchar(10) not null check (side in ('main','branch')),
  permissions jsonb not null default '[]'::jsonb check (jsonb_typeof(permissions)='array'),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name varchar(120) not null default '', email varchar(254) not null unique,
  role_key varchar(40) not null default 'pending',
  permissions jsonb null check (permissions is null or jsonb_typeof(permissions)='array'),
  branch_id bigint null references public.branches(id) on delete restrict,
  active boolean not null default false, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists profiles_branch_idx on public.profiles(branch_id);

create table if not exists public.categories (
  id bigint generated by default as identity primary key, name varchar(80) not null unique,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.suppliers (
  id bigint generated by default as identity primary key, name varchar(120) not null unique,
  contact varchar(120) not null default '', phone varchar(40) not null default '', active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.items (
  id bigint generated by default as identity primary key, code varchar(20) not null unique,
  name varchar(160) not null, category_id bigint not null references public.categories(id) on delete restrict,
  unit varchar(30) not null, min_stock integer not null default 0 check (min_stock>=0),
  last_unit_cost numeric(12,2) null check (last_unit_cost is null or last_unit_cost>=0), active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists items_category_idx on public.items(category_id);

create table if not exists public.app_settings (
  id integer primary key default 1 check (id=1), company_name varchar(120) not null default 'Our Company',
  branch_module_enabled boolean not null default false, audit_logging_enabled boolean not null default true,
  petty_cash_low_level numeric(12,2) not null default 2000 check (petty_cash_low_level>=0),
  stock_retention_lock_until timestamptz null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
insert into public.app_settings(id) values (1) on conflict (id) do nothing;
create table if not exists public.counters (key varchar(60) primary key, seq integer not null default 0 check (seq>=0));

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key, user_id uuid null references public.profiles(id) on delete set null,
  action varchar(60) not null, record_type varchar(40) not null default '', record_id varchar(40) not null default '',
  old_value jsonb null, new_value jsonb null, ip varchar(64) not null default '', created_at timestamptz not null default now()
);
create index if not exists audit_created_idx on public.audit_logs(created_at desc,id desc);

create table if not exists public.purchases (
  id bigint generated by default as identity primary key, number varchar(30) not null unique,
  supplier_id bigint not null references public.suppliers(id) on delete restrict, purchase_date date not null,
  invoice_ref varchar(80) not null default '', branch_id bigint null references public.branches(id) on delete restrict,
  status varchar(20) not null default 'ordered' check (status in ('ordered','partly_received','received','cancelled')),
  notes varchar(500) not null default '', created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists purchases_branch_date_idx on public.purchases(branch_id,purchase_date desc,created_at desc);
create table if not exists public.purchase_lines (
  id bigint generated by default as identity primary key, purchase_id bigint not null references public.purchases(id) on delete cascade,
  item_id bigint not null references public.items(id) on delete restrict,
  quantity_ordered integer not null check (quantity_ordered>0), quantity_received integer not null default 0 check (quantity_received>=0),
  unit_cost numeric(12,2) not null check (unit_cost>=0), unique (purchase_id,item_id)
);

create table if not exists public.office_issues (
  id bigint generated by default as identity primary key, number varchar(30) not null unique,
  recipient varchar(120) not null, department varchar(120) not null default '', issue_date date not null,
  branch_id bigint null references public.branches(id) on delete restrict,
  status varchar(20) not null default 'issued' check (status in ('issued','cancelled')),
  purpose varchar(300) not null default '', issued_by uuid not null references public.profiles(id) on delete restrict,
  cancelled_by uuid null references public.profiles(id) on delete restrict, cancelled_at timestamptz null,
  cancel_reason varchar(200) not null default '', created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.office_issue_lines (
  id bigint generated by default as identity primary key, issue_id bigint not null references public.office_issues(id) on delete cascade,
  item_id bigint not null references public.items(id) on delete restrict, quantity integer not null check (quantity>0)
);

create table if not exists public.requests (
  id bigint generated by default as identity primary key, number varchar(30) not null unique,
  branch_id bigint not null references public.branches(id) on delete restrict,
  status varchar(20) not null default 'submitted' check (status in ('submitted','approved','partly_approved','rejected','completed','cancelled')),
  notes varchar(300) not null default '', requested_by uuid not null references public.profiles(id) on delete restrict,
  reviewed_by uuid null references public.profiles(id) on delete restrict, reviewed_at timestamptz null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists requests_branch_status_idx on public.requests(branch_id,status,created_at desc);
create table if not exists public.request_lines (
  id bigint generated by default as identity primary key, request_id bigint not null references public.requests(id) on delete cascade,
  item_id bigint not null references public.items(id) on delete restrict, quantity_requested integer not null check (quantity_requested>0),
  quantity_approved integer not null default 0 check (quantity_approved>=0), quantity_dispatched integer not null default 0 check (quantity_dispatched>=0),
  reason varchar(200) not null default '', unique (request_id,item_id)
);

create table if not exists public.dispatches (
  id bigint generated by default as identity primary key, reference varchar(30) not null unique,
  request_id bigint null references public.requests(id) on delete restrict,
  destination_id bigint not null references public.branches(id) on delete restrict, dispatch_date date not null,
  status varchar(30) not null default 'in_transit' check (status in ('in_transit','received','received_with_differences','closed')),
  dispatched_by uuid not null references public.profiles(id) on delete restrict,
  received_by uuid null references public.profiles(id) on delete restrict, received_at timestamptz null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists dispatch_destination_status_idx on public.dispatches(destination_id,status,dispatch_date desc);
create table if not exists public.dispatch_lines (
  id bigint generated by default as identity primary key, dispatch_id bigint not null references public.dispatches(id) on delete cascade,
  item_id bigint not null references public.items(id) on delete restrict, quantity_sent integer not null check (quantity_sent>0),
  quantity_received integer not null default 0 check (quantity_received>=0), quantity_damaged integer not null default 0 check (quantity_damaged>=0),
  quantity_short integer not null default 0 check (quantity_short>=0), note varchar(200) not null default '', unique (dispatch_id,item_id)
);

create table if not exists public.stock_ledger (
  id bigint generated by default as identity primary key, item_id bigint not null references public.items(id) on delete restrict,
  branch_id bigint null references public.branches(id) on delete restrict, in_transit boolean not null default false,
  quantity_change integer not null check (quantity_change<>0),
  type varchar(20) not null check (type in ('purchase_receipt','dispatch_out','branch_receipt','office_issue','adjustment','reversal','opening_balance')),
  source_model varchar(30) not null default '', source_id varchar(40) not null default '', reason varchar(200) not null default '',
  note varchar(200) not null default '', reversal_of bigint null references public.stock_ledger(id) on delete restrict,
  created_by uuid null references public.profiles(id) on delete restrict, created_at timestamptz not null default now(),
  check ((branch_id is null)=in_transit)
);
create index if not exists stock_item_branch_idx on public.stock_ledger(item_id,branch_id);
create index if not exists stock_branch_created_idx on public.stock_ledger(branch_id,created_at desc,id desc);
create index if not exists stock_created_idx on public.stock_ledger(created_at desc,id desc);

create table if not exists public.petty_cash_requests (
  id bigint generated by default as identity primary key, number varchar(30) not null unique,
  branch_id bigint not null references public.branches(id) on delete restrict,
  amount_requested numeric(12,2) not null check (amount_requested>0), amount_approved numeric(12,2) not null default 0 check (amount_approved>=0),
  purpose varchar(300) not null default '', status varchar(20) not null default 'submitted' check (status in ('submitted','approved','rejected','cancelled')),
  requested_by uuid not null references public.profiles(id) on delete restrict, reviewed_by uuid null references public.profiles(id) on delete restrict,
  reviewed_at timestamptz null, review_note varchar(200) not null default '', created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists petty_cash_request_branch_idx on public.petty_cash_requests(branch_id,status,created_at desc);
create table if not exists public.petty_cash_entries (
  id bigint generated by default as identity primary key, branch_id bigint not null references public.branches(id) on delete restrict,
  type varchar(20) not null check (type in ('top_up','expense','reversal')), amount numeric(12,2) not null check (amount<>0),
  description varchar(300) not null default '', entry_date date not null,
  request_id bigint null references public.petty_cash_requests(id) on delete restrict,
  reversal_of bigint null unique references public.petty_cash_entries(id) on delete restrict,
  created_by uuid not null references public.profiles(id) on delete restrict, created_at timestamptz not null default now(),
  check ((type='expense' and amount<0) or (type<>'expense' and amount>0))
);
create index if not exists petty_cash_entry_branch_date_idx on public.petty_cash_entries(branch_id,entry_date desc,id desc);

